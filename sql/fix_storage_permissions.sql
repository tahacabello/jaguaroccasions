-- 1. إيقاف السياسة القديمة التي تتطلب الحساب البريدي للأدمن
DROP POLICY IF EXISTS "Allow admins full control over product-images" ON storage.objects;

-- 2. إنشاء سياسة أمان جديدة تمنح الصلاحية الكاملة للـ Anon والزوار لرفع وتعديل المرفقات
CREATE POLICY "Allow public full control over product-images" ON storage.objects
  FOR ALL TO anon, authenticated
  USING (bucket_id = 'product-images')
  WITH CHECK (bucket_id = 'product-images');
